const keys = Object.keys(en);
const locales = Object.keys(dictionaries);

mkdirSync(outDir, { recursive: true });

for (const locale of locales) {
  const dict = dictionaries[locale];
  for (const key of keys) {
    if (!(key in dict)) {
      throw new Error(`Missing key ${key} in ${locale}`);
    }
  }
  for (const key of Object.keys(dict)) {
    if (!keys.includes(key)) {
      throw new Error(`Unknown key ${key} in ${locale}`);
    }
  }

  const fileBase = locale;
  const constName = `messages_${locale.replace(/-/g, "_")}`;
  const lines = [
    `import type { WidgetMessages } from "../types";`,
    ``,
    `export const ${constName}: WidgetMessages = {`,
  ];

  for (const key of keys) {
    const value = dict[key].replace(/\\/g, "\\\\").replace(/"/g, '\\"');
    lines.push(`  ${key}: "${value}",`);
  }

  lines.push(`};`, ``, `export default ${constName};`, ``);
  writeFileSync(join(outDir, `${fileBase}.ts`), lines.join("\n"), "utf8");
}

console.log(`Wrote ${locales.length} locale dictionaries to ${outDir}`);
