#!/usr/bin/env node
/**
 * Writes apps/web-compatible .env.local from `supabase status -o env`
 * and seeds demo media (logo + attachment bytes) into local Storage.
 *
 * Usage (from repo root, after `supabase start` / `supabase db reset`):
 *   pnpm demo:prepare
 */
import { spawnSync } from "node:child_process";
import { writeFileSync, existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: "utf8",
    shell: process.platform === "win32",
    ...options,
  });
  if (result.status !== 0) {
    const detail = (result.stderr || result.stdout || "").trim();
    throw new Error(`${command} ${args.join(" ")} failed${detail ? `:\n${detail}` : ""}`);
  }
  return result.stdout ?? "";
}

function parseEnv(raw) {
  const env = {};
  for (const line of raw.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq);
    let value = trimmed.slice(eq + 1);
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

function ensureSecret(existing, bytes = 32) {
  if (typeof existing === "string" && existing.length >= 32) {
    return existing;
  }
  return randomBytes(bytes).toString("base64");
}

function main() {
  console.log("Reading local Supabase credentials…");
  const status = parseEnv(run("supabase", ["status", "-o", "env"]));

  const apiUrl = status.API_URL || status.NEXT_PUBLIC_SUPABASE_URL;
  const anonKey = status.ANON_KEY || status.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  const serviceKey = status.SERVICE_ROLE_KEY || status.SUPABASE_SERVICE_ROLE_KEY;
  const jwtSecret = status.JWT_SECRET || status.SUPABASE_JWT_SECRET;

  if (!apiUrl || !anonKey || !serviceKey || !jwtSecret) {
    throw new Error(
      "supabase status did not provide API_URL / ANON_KEY / SERVICE_ROLE_KEY / JWT_SECRET",
    );
  }

  const rootEnvPath = resolve(root, ".env.local");
  const webEnvPath = resolve(root, "apps/web/.env.local");
  const previous = existsSync(rootEnvPath)
    ? parseEnv(readFileSync(rootEnvPath, "utf8"))
    : existsSync(webEnvPath)
      ? parseEnv(readFileSync(webEnvPath, "utf8"))
      : {};

  const lines = [
    "# Generated by scripts/prepare-local-demo.mjs — local demo only",
    "NODE_ENV=development",
    "NEXT_PUBLIC_APP_URL=http://localhost:3000",
    `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
    `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
    `SUPABASE_JWT_SECRET=${jwtSecret}`,
    `AUTH_COOKIE_SECRET=${ensureSecret(previous.AUTH_COOKIE_SECRET)}`,
    `WIDGET_EMBED_SECRET=${ensureSecret(previous.WIDGET_EMBED_SECRET)}`,
    `RATE_LIMIT_SECRET=${ensureSecret(previous.RATE_LIMIT_SECRET)}`,
    "AI_ALLOW_MOCK_PROVIDER=true",
    "",
  ];

  const contents = lines.join("\n");
  writeFileSync(rootEnvPath, contents, "utf8");
  writeFileSync(webEnvPath, contents, "utf8");
  console.log(`Wrote ${rootEnvPath}`);
  console.log(`Wrote ${webEnvPath}`);

  console.log("Seeding demo media (logo + attachment)…");
  run("node", ["scripts/seed-demo-media.mjs"], { stdio: "inherit" });

  console.log("\nLocal demo prep complete.");
  console.log("Next (two terminals):");
  console.log("  1) pnpm local:refresh && pnpm dev");
  console.log("  2) pnpm demo:host");
  console.log("Then open http://localhost:3001 and confirm the launcher (bottom-right).");
  console.log("Optional: pnpm demo:check");
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
